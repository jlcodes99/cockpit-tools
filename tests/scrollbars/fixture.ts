createRoot(dropdown).render(React.createElement(SingleSelectDropdown, { value: '0', options: Array.from({ length: 50 }, (_, i) => ({ value: String(i), label: 'Option ' + i })), onChange: () => { }, menuMaxHeight: 150 }));
